// Title (designation) table of the Perfil / Títulos phase -> src/lobby/core/titleData.ts
//   node export-titles.mjs
// Sources: extracted/pef-cross/br/DesignationValue.json (pef/export-cross.mjs; DesignationSet = the PBCross title table,
// DesignationValue effect values), system_titles (requirements the server-ts handleTitleChange checks): --server
// old/runtime/db-init/022_migration_system_titles_20260725.sql (private layout) or db/init/001_init.sql (public layout). Tree: PBCross UI_Project_Profile Designation_Tree_Slot<N>; the Cross exe
// links slot N to the DesignationSet whose _Type-set index is N (profile.ts nodeTitle), so TREE_NODES needs no layout file.
import { TOOLS, generatedPath, oldServerPathOpt, dbInitPath, pefDir } from './lib/paths.mjs';
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const pef = JSON.parse(readFileSync(pefDir('br', 'DesignationValue.json'), "utf8"));
const migration = oldServerPathOpt("runtime", "db-init", "022_migration_system_titles_20260725.sql");
const sql = readFileSync(migration && existsSync(migration) ? migration : dbInitPath("001_init.sql"), "utf8");
// 022: INSERT tuples. 001 (pg_dump): tab-separated COPY rows, turned into the same "(a, b, ...)" tuples
const block = migration && existsSync(migration)
  ? sql.slice(sql.indexOf("INSERT INTO system_titles"), sql.indexOf("INSERT INTO system_title_awards"))
  : (() => { const start = sql.indexOf("COPY public.system_titles ("); return sql.slice(start, sql.indexOf("\n\\.", start)).replace(/\t/g, ", ").replace(/^(\d.*)$/gm, "($1)"); })();

// effect ids (DESIGNATION_ID) decoded from the exe (tools/designation-effects.json): id = family base + level - 1, value = pef key
const fx = JSON.parse(readFileSync(join(TOOLS, "designation-effects.json"), "utf8"));
const effects = {}; // id -> [STR_HEADER_<key>, pef key | ""]
for (const [id, str] of Object.entries(fx.strings)) effects[id] = [str, ""];
for (const [base, fam] of fx.families) {
  for (let l = 1; l <= 5; l++) {
    const key = `${fam}_${l}`;
    if (!(key in pef)) throw new Error(`pef has no ${key}`);
    effects[base + l - 1] = [fx.strings[base + l - 1] ?? "", key];
  }
}

// system_titles rows: (id, class_id, ribbon, ensign, medal, master_medal, rank, slot, req1, req2)
const reqs = new Map();
for (const m of block.matchAll(/^\s*\((\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (\d+), (\d+)\)/gm)) {
  const [id, classId, ribbon, ensign, medal, master, rank, slot, req1, req2] = m.slice(1).map(Number);
  reqs.set(id, { classId, ribbon, ensign, medal, master, rank, slot, req1, req2 });
}
if (reqs.size !== 44) throw new Error(`expected 44 system_titles rows, got ${reqs.size}`);

// wire id of a DesignationSet = its _Type (Set_10 "Sniper" _Type 14 = server title 14, requires 6 = Backup Soldier)
const titles = [];
for (const [key, s] of Object.entries(pef.DesignationSet)) {
  const set = Number(key.slice(4)), id = s._Type;
  const eff = (a) => a.map((f) => s[f] ?? 0).filter(Boolean);
  const weapon = [0, 1].filter((i) => s[`_AuthWeaponClass_${i}`]).map((i) => [s[`_AuthWeaponClass_${i}`], s[`_AuthWeaponNumber_${i}`]]);
  titles.push({ id, set, apply: s._ApplyType, plus: eff(["_PlusEffect_0", "_PlusEffect_1"]), minus: eff(["_MinusEffect_0", "_MinusEffect_1"]), add: eff(["_AddEffect_0", "_AddEffect_1"]), weapon, ...reqs.get(id) });
}
titles.sort((a, b) => a.id - b.id);
if (titles.some((t, i) => t.id !== i + 1 || !t.classId)) throw new Error("title ids are not 1..44");

// tree[k] = title of Designation_Tree_Slot<k+1> = the DesignationSet with set index k+1 (exe: slot N -> set N, profile.ts nodeTitle)
const tree = Array.from({ length: 44 }, (_, k) => titles.find((t) => t.set === k + 1)?.id ?? 0);
if (tree.some((t) => !t) || new Set(tree).size !== 44) throw new Error("tree is not a permutation of 1..44");

const num = (n) => String(n);
const out = `// GENERATED by tools/export-titles.mjs (do not edit). Title table of the Perfil / Títulos phase.
// id = wire id of 2376/2378/2380 (DesignationSet._Type); set = DesignationSet index (name key STR_TBL_DESIGNATION_NAME_NO<set-1>);
// plus/minus/add = effect ids (DESIGNATION_ID, exe table: see tools/designation-effects.json);
// weapon = [AuthWeaponClass, AuthWeaponNumber]; requirements = system_titles (server-ts profileHandlers loadTitles).
export interface TitleDef {
  id: number; set: number; apply: number; plus: number[]; minus: number[]; add: number[]; weapon: [number, number][];
  classId: number; ribbon: number; ensign: number; medal: number; master: number; rank: number; slot: number; req1: number; req2: number;
}
export const TITLES: readonly TitleDef[] = [
${titles.map((t) => `  { id: ${t.id}, set: ${t.set}, apply: ${t.apply}, plus: [${t.plus}], minus: [${t.minus}], add: [${t.add}], weapon: ${JSON.stringify(t.weapon)}, classId: ${t.classId}, ribbon: ${t.ribbon}, ensign: ${t.ensign}, medal: ${t.medal}, master: ${t.master}, rank: ${t.rank}, slot: ${t.slot}, req1: ${t.req1}, req2: ${t.req2} },`).join("\n")}
];
/** tree index NN = Designation_Tree_Slot<NN+1> (PBCross UI_Project_Profile) -> title id */
export const TREE_NODES: readonly number[] = [${tree.join(", ")}];
/** effect id -> [STR_HEADER_<key> text, DesignationValue.pef key ("" = no value)] (exe CDesignationValueSet 0x4d1a20 / 0x4d29d0) */
export const EFFECTS: Readonly<Record<number, readonly [string, string]>> = ${JSON.stringify(effects)};
/** effect ids the detail panel resolves through the weapon path (exe 0x4d4c20) */
export const AUTHORITY_EFFECTS: readonly number[] = ${JSON.stringify(fx.authority)};
/** DesignationValue.pef values by key (only the keys the effect ids use) */
export const EFFECT_VALUES: Readonly<Record<string, number>> = ${JSON.stringify(Object.fromEntries(Object.values(effects).map((e) => e[1]).filter(Boolean).map((k) => [k, pef[k]])))};
`;
writeFileSync(generatedPath("lobby/core/titleData.ts"), out);
console.log(`titleData.ts: ${titles.length} titles, ${Object.keys(effects).length} effects, tree ${tree.join(",")}`);
