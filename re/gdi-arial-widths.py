# GDI glyph advances of Arial as the i3Engine text measures them (Windows only: needs gdi32).
#   pbx re gdi-arial   -> src/lobby/ui/gdiArial.ts with --web, else out/generated
# i3TextAttrDX2::CreateEx (Cross i3SceneDx 0x10105b10) builds a LOGFONT with lfHeight = i3Gfx::FontPointToPixel(pt)
# (> 0 = cell height), the weight it is given, lfWidth 0, and i3GfxFontDX2::getGlyph (i3GfxDx 0x100b0430) stores each
# glyph's width = GetTextExtentPoint32A(dc, that one char) (_DrawFontToDrawTex 0x100ae820); _ArrangeText sums those.
# The line height is getGlyphHeight = the extent's cy (0x100b0216) = tmHeight.
# `em` = the CSS px size of Arial whose plain advances add up to the GDI ones over the PT-BR string table (char frequency of
# out/ui/cross/strings.json), measured against the face the browser draws (regular below 600, bold from 600).
import ctypes
import ctypes.wintypes as W
import json
import os
from collections import Counter

gdi = ctypes.windll.gdi32


class LOGFONTA(ctypes.Structure):
    _fields_ = [("lfHeight", W.LONG), ("lfWidth", W.LONG), ("lfEscapement", W.LONG), ("lfOrientation", W.LONG),
                ("lfWeight", W.LONG), ("lfItalic", W.BYTE), ("lfUnderline", W.BYTE), ("lfStrikeOut", W.BYTE),
                ("lfCharSet", W.BYTE), ("lfOutPrecision", W.BYTE), ("lfClipPrecision", W.BYTE), ("lfQuality", W.BYTE),
                ("lfPitchAndFamily", W.BYTE), ("lfFaceName", ctypes.c_char * 32)]


dc = gdi.CreateCompatibleDC(0)


def measure(height, weight):
    lf = LOGFONTA(lfHeight=height, lfWeight=weight, lfFaceName=b"Arial")
    font = gdi.CreateFontIndirectA(ctypes.byref(lf))
    old = gdi.SelectObject(dc, font)
    ws = []
    for c in range(256):
        sz = W.SIZE()
        gdi.GetTextExtentPoint32A(dc, bytes([c]), 1, ctypes.byref(sz))
        ws.append((sz.cx, sz.cy))
    gdi.SelectObject(dc, old)
    gdi.DeleteObject(font)
    return ws


# Latin-1 code points only (0x80..0x9f differ between cp1252 and Unicode: left to the browser)
CODES = [c for c in range(32, 256) if not 127 <= c < 160]
gen_path = os.path.join(os.environ["PB_WEB"], "src", "lobby", "ui", "gdiArial.ts") if os.environ.get("PB_WEB") else os.path.join(os.environ["PB_ASSETS"], "generated", "lobby", "ui", "gdiArial.ts")
strings = json.load(open(os.path.join(os.environ["PB_ASSETS"], "ui", "cross", "strings.json"), encoding="utf-8"))
freq = Counter(ch for v in strings.values() if isinstance(v, str) for ch in v if ord(ch) in CODES)
units = {w: measure(-2048, w) for w in (400, 700)}

tables = {}
for pt, cell in ((9, 12), (10, 13), (11, 15), (12, 16), (13, 17)):  # FontPointToPixel = round(pt * 96 / 72)
    for weight in (400, 600, 700):
        ws = measure(cell, weight)
        face = units[700 if weight >= 600 else 400]
        em = 2048 * sum(n * ws[ord(ch)][0] for ch, n in freq.items()) / sum(n * face[ord(ch)][0] for ch, n in freq.items())
        tables[f"{cell}/{weight}"] = {"h": ws[ord("A")][1], "em": round(em, 2),
                                      "w": "".join(chr(48 + ws[c][0]) if c in CODES else "0" for c in range(32, 256))}

lines = ["// Generated by tools/re/gdi-arial-widths.py (GDI on Windows): do not edit.",
         "// Arial advances as the i3Engine text measures them (GetTextExtentPoint32A per glyph, i3GfxDx 0x100b0430), key",
         "// \"<cell px>/<weight>\": h = line height (tmHeight), em = CSS px with the same average advance, w = width of code point",
         "// 32 + i as charCode(48 + px) (\"0\" = not in the table: 0x7f..0x9f).",
         "export const GDI_ARIAL: Record<string, { h: number; em: number; w: string }> = {"]
for k, v in tables.items():
    lines.append(f'  "{k}": {{ h: {v["h"]}, em: {v["em"]}, w: {json.dumps(v["w"])} }},')
lines.append("};")
open(gen_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
for k, v in tables.items():
    print(k, "h", v["h"], "em", v["em"])
